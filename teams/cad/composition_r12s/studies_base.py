def flank_fns(spine4):
    P = np.array(spine4, float); c, t, L = curve(P[:, :3], 3.0); rf, _ = spine_rfun(spine4); r = rf(t); order = np.argsort(c[:, 1])
    ys = c[order, 1]; xs = c[order, 0]; rr = r[order]; m = np.gradient(xs, ys + 1e-6 * np.arange(len(ys)))
    xc = lambda y: float(np.interp(y, ys, xs)); half = lambda y: float(np.interp(y, ys, rr) * np.sqrt(1 + np.interp(y, ys, m) ** 2))
    return xc, half, (c, t, r)

def meridians_gen(spine4, maw, n_side, seed, mask_c, mask_clear=118.0):
    """strand ribbing riding the spine (offset along the spine normal), kept clear of the maw (sd > 22) and the mask (>= 118 mm from its centre)."""
    rng = np.random.default_rng(seed); P = np.array(spine4, float); c, t, L = curve(P[:, :3], 6.0); rf, _ = spine_rfun(spine4); r = rf(t)
    tg = np.gradient(c[:, :2], axis=0); tg /= np.linalg.norm(tg, axis=1)[:, None]; nr = np.stack([-tg[:, 1], tg[:, 0]], 1); ad = maw_sd(maw, 12); out = []
    for sd in (-1, 1):
        for j in range(n_side):
            f = (j + 0.5 + rng.uniform(-0.15, 0.15)) / n_side; ph = rng.uniform(0, 6.28); pts = []
            t0 = rng.uniform(0.0, 0.05); t1 = rng.uniform(0.80, 0.92)
            for i in range(len(c)):
                if not (0.10 + t0 < t[i] < t1): continue
                W = r[i] - 8; o = f * W
                while o < W and ad(np.array([c[i, 0] + sd * nr[i, 0] * o]), np.array([c[i, 1] + sd * nr[i, 1] * o]))[0] < 22: o += 3
                p_ = c[i, :2] + sd * nr[i] * o + 3 * np.sin(i / 10 + ph) * nr[i]
                if np.hypot(*(p_ - np.array(mask_c))) < mask_clear: continue
                pts.append(tuple(p_))
            pts = pts[::2]
            if len(pts) >= 5: out.append(pts)
    return out

def roots_on_spine(spine4, u, side, frac=0.7):
    P = np.array(spine4, float); c, t, L = curve(P[:, :3], 3.0); rf, _ = spine_rfun(spine4); i = int(np.argmin(abs(t - u))); tg = np.gradient(c[:, :2], axis=0)[i]; tg /= np.linalg.norm(tg)
    n = np.array([-tg[1], tg[0]]); p = c[i, :2] + side * n * rf(t[i]) * frac; return (float(p[0]), float(p[1]))

